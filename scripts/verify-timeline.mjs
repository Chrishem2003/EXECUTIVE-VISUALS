import assert from "node:assert/strict";
import { addClip, addMarker, addTrack, createTimeline, evaluateSpeedCurve, integrateSpeedCurve, moveClip, normalizeAudioMasteringSettings, rational, seconds, sourceElapsedSeconds, splitClip, toOpenTimelineIo, timelineElapsedForSourceElapsed, trimClip, validateTimeline } from "../src/core/timeline.ts";
import { analyzeTimelineQuality } from "../src/core/timeline-quality.ts";
import { normalizeAudioAutomation, evaluateAudioAutomation, buildGainAutomationExpression } from "../src/core/audio-automation.ts";

let timeline=createTimeline("project-1","timeline-1","Pilot episode",{numerator:24,denominator:1});
timeline=addTrack(timeline,{id:"v1",name:"Video 1",kind:"video",enabled:true,locked:false,clips:[]});
timeline=addTrack(timeline,{id:"v2",name:"Overlays",kind:"overlay",enabled:true,locked:false,clips:[]});
timeline=addClip(timeline,"v1",{id:"clip-a",assetId:"asset-a",name:"Opening",sourceRange:{start:rational(0,24),duration:rational(240,24)},timelineStart:rational(0,24),duration:rational(240,24),enabled:true});
timeline=addClip(timeline,"v1",{id:"clip-b",assetId:"asset-b",name:"Second scene",sourceRange:{start:rational(0,24),duration:rational(120,24)},timelineStart:rational(300,24),duration:rational(120,24),enabled:true});
assert.equal(validateTimeline(timeline).valid,true);
timeline=trimClip(timeline,"v1","clip-a",24,24);
const trimmed=timeline.tracks[0].clips.find(x=>x.id==="clip-a");
assert.equal(trimmed.sourceRange.start.value,24);
assert.equal(trimmed.sourceRange.duration.value,192);
assert.equal(trimmed.timelineStart.value,24);
assert.equal(trimmed.duration.value,192);
timeline=splitClip(timeline,"v1","clip-a",120,"clip-a-part-b");
assert.equal(timeline.tracks[0].clips.length,3);
const partB=timeline.tracks[0].clips.find(x=>x.id==="clip-a-part-b");
assert.equal(partB.sourceRange.start.value,120);
assert.equal(partB.sourceRange.duration.value,96);
assert.equal(partB.timelineStart.value,120);
timeline=moveClip(timeline,"v1","clip-b","v2",500);
assert.equal(timeline.tracks[0].clips.some(x=>x.id==="clip-b"),false);
assert.equal(timeline.tracks[1].clips[0].timelineStart.value,500);
timeline=moveClip(timeline,"v1","clip-a-part-b","v1",150);
assert.equal(timeline.tracks[0].clips.some(x=>x.id==="clip-a-part-b"),true);
assert.equal(validateTimeline(timeline).valid,true);
timeline=addMarker(timeline,{id:"marker-1",name:"Review hook",start:rational(144,24),color:"YELLOW",note:"Check the opening"});
const interchange=toOpenTimelineIo(timeline);
assert.equal(interchange.OTIO_SCHEMA,"Timeline.1");
assert.equal(interchange.tracks.children.length,2);
assert.equal(interchange.markers.length,1);
assert.equal(interchange.markers[0].name,"Review hook");
assert.ok(JSON.stringify(interchange).includes("asset://asset-a"));
const automationPoints=normalizeAudioAutomation([{timeSeconds:1,gainDb:-12,pan:-1,interpolation:"linear"},{timeSeconds:3,gainDb:-24,pan:1,interpolation:"step"}]);
assert.equal(automationPoints.length,2);
assert.ok(Math.abs(evaluateAudioAutomation(automationPoints,.5,"gainDb",0)+6)<1e-9);
assert.equal(evaluateAudioAutomation(automationPoints,4,"pan",0),1);
assert.match(buildGainAutomationExpression(automationPoints,0),/if\(lt\(t,1\)/);
const audioTimeline=createTimeline("project-audio","timeline-audio","Audio automation");
let audioTracks=addTrack(audioTimeline,{id:"video",name:"Video",kind:"video",enabled:true,locked:false,clips:[]});
audioTracks=addTrack(audioTracks,{id:"audio",name:"Audio",kind:"audio",enabled:true,locked:false,clips:[]});
audioTracks=addClip(audioTracks,"audio",{id:"voice",assetId:"voice-asset",name:"Voice",sourceRange:{start:rational(0,1),duration:rational(4,1)},timelineStart:rational(0,1),duration:rational(4,1),enabled:true,gainDb:-3,pan:-.25,audioAutomation:automationPoints});
assert.equal(validateTimeline(audioTracks).valid,true);
const audioOtio=toOpenTimelineIo(audioTracks);
assert.deepEqual(audioOtio.tracks.children[1].children[0].metadata.executiveVisuals.audioAutomation,automationPoints);
assert.equal(audioOtio.tracks.children[1].children[0].metadata.executiveVisuals.pan,-.25);
const invalidAudioTimeline={...audioTracks,tracks:audioTracks.tracks.map(track=>track.id==="audio"?{...track,clips:[{...track.clips[0],audioAutomation:[{timeSeconds:5,gainDb:-3}]}]}:track)};
assert.equal(validateTimeline(invalidAudioTimeline).issues.some(issue=>issue.code==="invalid_audio_automation"),true);
assert.throws(()=>normalizeAudioAutomation(Array.from({length:257},(_,index)=>({timeSeconds:index,gainDb:0}))),/256/);

const masteredTimeline={...timeline,audioMastering:normalizeAudioMasteringSettings({enabled:true,profile:"ebu-r128",loudnessRange:9,truePeak:-1})};
const masteredInterchange=toOpenTimelineIo(masteredTimeline);
const persistedMasteredTimeline=JSON.parse(JSON.stringify(masteredTimeline));
assert.deepEqual(persistedMasteredTimeline.audioMastering,masteredTimeline.audioMastering,"JSON persistence must retain the selected mastering profile and targets");
assert.deepEqual(normalizeAudioMasteringSettings(persistedMasteredTimeline.audioMastering),masteredTimeline.audioMastering,"restored mastering settings must normalize to the same saved profile and targets");
assert.deepEqual(masteredInterchange.metadata.executiveVisuals.audioMastering,masteredTimeline.audioMastering,"OTIO export must preserve the mastering delivery contract");
const legacyInterchange=toOpenTimelineIo(timeline);
assert.equal(legacyInterchange.metadata.executiveVisuals.audioMastering,null,"legacy timelines export with an explicit empty mastering contract");
assert.ok(seconds(rational(48,24))===2);

const webMastering=normalizeAudioMasteringSettings({enabled:true});
assert.deepEqual(webMastering,{enabled:true,profile:"web-podcast",integratedLoudness:-16,loudnessRange:11,truePeak:-1.5,dualMono:false});
const fixedWebMastering=normalizeAudioMasteringSettings({enabled:true,profile:"web-podcast",integratedLoudness:-23,loudnessRange:10,truePeak:-2});
assert.equal(fixedWebMastering.integratedLoudness,-16,"Web / Podcast must override a submitted broadcast target");
const broadcastMastering=normalizeAudioMasteringSettings({enabled:true,profile:"ebu-r128",integratedLoudness:-16,loudnessRange:8,truePeak:-1,dualMono:true});
assert.equal(broadcastMastering.integratedLoudness,-23,"EBU R128 must override a submitted Web target");
assert.equal(broadcastMastering.profile,"ebu-r128");
assert.throws(()=>normalizeAudioMasteringSettings({enabled:true,profile:"ebu-r128",truePeak:-0.5}),/EBU R128 true peak must not exceed -1 dBTP/);
assert.equal(normalizeAudioMasteringSettings({enabled:true,profile:"ebu-r128",truePeak:-1}).truePeak,-1);
const customMastering=normalizeAudioMasteringSettings({enabled:false,profile:"custom",integratedLoudness:-18.5,loudnessRange:7,truePeak:-2,dualMono:false});
assert.equal(customMastering.integratedLoudness,-18.5,"Custom profile must preserve its explicit target");
assert.throws(()=>normalizeAudioMasteringSettings({enabled:true,profile:"unknown",integratedLoudness:-16}),/supported audio mastering profile/);
assert.throws(()=>normalizeAudioMasteringSettings({enabled:true,profile:"custom",integratedLoudness:-80}),/Mastering targets must be within/);
assert.throws(()=>normalizeAudioMasteringSettings({enabled:true,profile:"custom",integratedLoudness:-16,loudnessRange:0,truePeak:-1}),/Mastering targets must be within/);

const overlap={...timeline,tracks:timeline.tracks.map(track=>track.id==="v1"?{...track,clips:[...track.clips,{id:"overlap",assetId:"asset-x",name:"Overlap",sourceRange:{start:rational(0,24),duration:rational(60,24)},timelineStart:rational(60,24),duration:rational(60,24),enabled:true}]}:track)};
assert.equal(validateTimeline(overlap).issues.some(x=>x.code==="overlap"),true);
assert.throws(()=>toOpenTimelineIo(overlap),/overlap/);
const speedCurve=[{timeSeconds:0,speed:1},{timeSeconds:2,speed:2},{timeSeconds:4,speed:1}];
assert.equal(evaluateSpeedCurve(speedCurve,1),1.5);
assert.equal(integrateSpeedCurve(speedCurve,4),6);
const speedTimeline=createTimeline("project-speed","timeline-speed","Variable speed",{numerator:24,denominator:1});
const speedTrack=addTrack(speedTimeline,{id:"speed-video",name:"Speed ramp",kind:"video",enabled:true,locked:false,clips:[]});
const speedClip={id:"speed-ramp",assetId:"speed-source",name:"Speed ramp",sourceRange:{start:rational(0,24),duration:rational(144,24)},timelineStart:rational(0,24),duration:rational(96,24),enabled:true,speed:1,speedCurve};
const speedAdded=addClip(speedTrack,"speed-video",speedClip);
assert.equal(validateTimeline(speedAdded).valid,true);
assert.equal(sourceElapsedSeconds(speedClip,2),3);
assert.equal(timelineElapsedForSourceElapsed(speedClip,3),2);
const splitSpeed=splitClip(speedAdded,"speed-video","speed-ramp",48,"speed-ramp-b");
assert.equal(seconds(splitSpeed.tracks[0].clips[0].sourceRange.duration),3);
assert.equal(seconds(splitSpeed.tracks[0].clips[1].sourceRange.start),3);
assert.equal(splitSpeed.tracks[0].clips[1].speedCurve[0].speed,2);
const trimmedSpeed=trimClip(speedAdded,"speed-video","speed-ramp",24,0);
assert.ok(Math.abs(seconds(trimmedSpeed.tracks[0].clips[0].sourceRange.start)-1.25)<1e-9);
assert.ok(Math.abs(seconds(trimmedSpeed.tracks[0].clips[0].sourceRange.duration)-4.75)<1e-9);
assert.equal(trimmedSpeed.tracks[0].clips[0].speedCurve[0].speed,1.5);
const invalidSpeedCurve={...speedAdded,tracks:speedAdded.tracks.map(track=>({...track,clips:track.clips.map(clip=>({...clip,speedCurve:[{timeSeconds:0,speed:1},{timeSeconds:1,speed:5}]}))}))};
assert.ok(validateTimeline(invalidSpeedCurve).issues.some(issue=>issue.code==="invalid_speed_curve"));
const malformedSpeedCurve={...speedAdded,tracks:speedAdded.tracks.map(track=>({...track,clips:track.clips.map(clip=>({...clip,speedCurve:[{timeSeconds:0,speed:1},null]}))}))};
assert.ok(validateTimeline(malformedSpeedCurve).issues.some(issue=>issue.code==="invalid_speed_curve"));

const locked={...timeline,tracks:timeline.tracks.map(track=>track.id==="v1"?{...track,locked:true}:track)};
assert.throws(()=>moveClip(locked,"v1","clip-a","v2",600),/locked/);


const qualityTimeline=createTimeline("project-1","quality-1","Quality check",{numerator:24,denominator:1});
let quality=addTrack(qualityTimeline,{id:"quality-video",name:"Picture",kind:"video",enabled:true,locked:false,clips:[]});
quality=addTrack(quality,{id:"quality-overlay",name:"Graphics",kind:"overlay",enabled:true,locked:false,clips:[]});
quality=addClip(quality,"quality-video",{id:"quality-clip-1",assetId:"quality-asset",name:"Opening",sourceRange:{start:rational(0,24),duration:rational(48,24)},timelineStart:rational(0,24),duration:rational(48,24),enabled:true});
quality=addClip(quality,"quality-video",{id:"quality-clip-2",assetId:"quality-asset",name:"Second shot",sourceRange:{start:rational(72,24),duration:rational(48,24)},timelineStart:rational(72,24),duration:rational(48,24),enabled:true});
quality=addMarker(quality,{id:"quality-marker",name:"Late review",start:rational(240,24)});
const findings=analyzeTimelineQuality(quality,[{id:"quality-asset",name:"Source",mediaType:"video/mp4",metadata:{probe:{format:{duration:4}}}}]);
const codes=new Set(findings.map(item=>item.code));
assert.ok(codes.has("PICTURE_GAP"));
assert.ok(codes.has("NO_AUDIO"));
assert.ok(codes.has("NO_CAPTIONS"));
assert.ok(codes.has("EMPTY_OVERLAY_TRACK"));
assert.ok(codes.has("MARKER_AFTER_SEQUENCE"));
assert.ok(codes.has("SEQUENCE_DURATION"));
const outOfRange=analyzeTimelineQuality(quality,[{id:"quality-asset",metadata:{probe:{format:{duration:2}}}}]);
assert.ok(outOfRange.some(item=>item.code==="SOURCE_RANGE_EXCEEDS_MEDIA"));
assert.ok(analyzeTimelineQuality(quality,[]).some(item=>item.code==="ASSET_NOT_IN_LIBRARY"));
assert.ok(analyzeTimelineQuality(null).some(item=>item.code==="NO_SEQUENCE"));

console.log("Timeline engine checks passed: rational timing, source trims, split, cross-track and same-track moves, overlap protection, markers and editorial interchange export.");
