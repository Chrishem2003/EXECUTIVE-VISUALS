import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

const render=await readFile("render.yaml","utf8");
const docker=await readFile("Dockerfile","utf8");
const server=await readFile("server/index.mjs","utf8");
const pkg=JSON.parse(await readFile("package.json","utf8"));
assert.match(render,/name: executive-visuals-staging/);
assert.match(render,/plan: starter/);
assert.match(render,/region: frankfurt/);
assert.match(render,/mountPath: \/var\/data/);
assert.match(render,/sizeGB: 1/);
assert.match(render,/DATA_DIR[\s\S]*?value: \/var\/data/);
assert.match(render,/DB_FILE[\s\S]*?value: \/var\/data\/executive-visuals\.sqlite/);
assert.match(render,/MEDIA_ROOT[\s\S]*?value: \/var\/data\/media/);
assert.match(render,/REQUIRE_PERSISTENT_DATA_DIR[\s\S]*?value: "true"/);
assert.match(render,/AUTH_MODE[\s\S]*?value: supabase/);
assert.match(render,/SUPABASE_URL[\s\S]*?sync: false/);
assert.match(render,/SUPABASE_PUBLISHABLE_KEY[\s\S]*?sync: false/);
assert.doesNotMatch(render,/AUTH_MODE[\s\S]*?value: local/);
assert.match(docker,/FROM node:24\.22\.1-bookworm-slim AS build/);
assert.match(docker,/apt-get install[^\n]*ffmpeg/);
assert.match(docker,/RUN npm ci/);
assert.match(docker,/RUN npm run build/);
assert.match(docker,/FROM node:24\.22\.1-bookworm-slim AS runtime/);
assert.equal((docker.match(/FROM node:24\.22\.1-bookworm-slim AS (?:build|runtime)/g)||[]).length,2);
assert.match(docker,/sha256sum --check/);
assert.match(docker,/TARGETARCH/);
assert.match(docker,/--exclude=server\/tests/);
assert.match(docker,/COPY --from=build \/app\/runtime-server/);
assert.doesNotMatch(docker,/COPY --from=build \/app\/server/);
assert.match(docker,/COPY --from=build \/app\/dist/);
assert.match(docker,/CMD \["npm","start"\]/);
assert.match(server,/REQUIRE_PERSISTENT_DATA_DIR/);
assert.match(server,/isWithinDataDir\(DB_FILE\)/);
assert.equal(pkg.scripts.start,"node server/index.mjs");
assert.ok(pkg.scripts.build.includes("npm run verify:deployment"));
assert.match(docker,/ENV C2PA_LIBRARY_PATH=\/opt\/c2pa\/index\.node/);
console.log("Deployment guard passed: patched Node 24.22.1, checksum-pinned CAI native runtime, test-fixture exclusion, FFmpeg, external staging auth and durable storage.");
